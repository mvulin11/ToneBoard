import UIKit
import SwiftUI
import Combine
import KeyboardKit

// MARK: - Smart AI Autocomplete Provider
// Replaces LocalAutocompleteProvider to mix instant local typing with AI predictions
class SmartAutocompleteProvider: AutocompleteService {
    var locale: Locale = .current
    var canIgnoreWords: Bool { false }
    var canLearnWords: Bool { false }
    var ignoredWords: [String] { [] }
    var learnedWords: [String] { [] }
    
    var aiPredictions: [String] = []
    
    func hasIgnoredWord(_ word: String) -> Bool { false }
    func hasLearnedWord(_ word: String) -> Bool { false }
    func ignoreWord(_ word: String) {}
    func learnWord(_ word: String) {}
    func removeIgnoredWord(_ word: String) {}
    func unlearnWord(_ word: String) {}
    func ignore(_ suggestion: KeyboardKit.Autocomplete.Suggestion) {}
    func learn(_ suggestion: KeyboardKit.Autocomplete.Suggestion) {}
    
    func autocomplete(_ text: String) async throws -> KeyboardKit.Autocomplete.Result {
        let words = text.components(separatedBy: .whitespacesAndNewlines)
        let currentWord = words.last ?? ""
        var suggestions: [Autocomplete.Suggestion] = []
        
        // Return strictly the AI predictions that were generated by the remote LLM
        for prediction in aiPredictions {
            if !suggestions.contains(where: { $0.text.lowercased() == prediction.lowercased() }) {
                suggestions.append(Autocomplete.Suggestion(text: prediction))
            }
        }
        
        return Autocomplete.Result(inputText: currentWord, suggestions: Array(suggestions.prefix(3)))
    }
}

// MARK: - Main Keyboard Controller
class KeyboardViewController: KeyboardInputViewController {
    
    let appGroupID = "group.com.matt.cpplearning.ToneBoard"
    
    private var isPolishing: Bool = false
    private var lastObservedText = ""
    
    private var activeApiTask: Task<Void, Never>?
    
    private lazy var smartProvider = SmartAutocompleteProvider()
    private var hasAlertedNoKey = false
    
    override func viewDidLoad() {
        super.viewDidLoad()
        
        state.feedbackContext.settings.isHapticFeedbackEnabled = true
        state.feedbackContext.hapticConfiguration.press = .heavyImpact
        state.feedbackContext.hapticConfiguration.release = .heavyImpact
        
        state.autocompleteContext.settings.isAutocompleteEnabled = true
        state.autocompleteContext.settings.isAutocorrectEnabled = true
        services.autocompleteService = smartProvider
    }
    
    override func textDidChange(_ textInput: UITextInput?) {
        super.textDidChange(textInput)
        
        let currentText = textDocumentProxy.documentContextBeforeInput ?? ""
        
        if isPolishing { return }
        if currentText == lastObservedText { return }
        lastObservedText = currentText
        
        let trimmed = currentText.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty {
            smartProvider.aiPredictions.removeAll()
            updateAutocompleteUI()
            return
        }
        
        // Option C: Word-Boundary AI Only.
        // We removed UITextChecker so there are no false-positive local overwrites.
        // But firing local LM Studio queries on every keystroke thrashes the KV Cache and causes lag.
        // By restricting the AI inference to only trigger when completing a word, the Mac 
        // processes exactly 1 context evaluation per word perfectly inline with typing speed.
        guard let lastChar = currentText.last else { return }
        
        if lastChar.isWhitespace || lastChar.isNewline || lastChar.isPunctuation {
            self.activeApiTask?.cancel()
            
            self.activeApiTask = Task { @MainActor [weak self] in
                guard let self = self else { return }
                await self.triggerAutoPolish(draftText: currentText)
            }
        }
    }
    
    // Forces the UI to refresh its predictions based on the AI Response
    private func updateAutocompleteUI() {
        Task { @MainActor in
            let currentWord = textDocumentProxy.documentContextBeforeInput?.components(separatedBy: .whitespacesAndNewlines).last ?? ""
            if let result = try? await smartProvider.autocomplete(currentWord) {
                state.autocompleteContext.update(with: result)
            }
        }
    }
    
    @MainActor
    private func triggerAutoPolish(draftText: String) async {
        let defaults = UserDefaults(suiteName: appGroupID)
        let savedKey = defaults?.string(forKey: "apiKey") ?? ""
        let tone = defaults?.string(forKey: "selectedTone") ?? "Professional"
        let apiUrl = defaults?.string(forKey: "apiUrl") ?? "http://127.0.0.1:1234/v1"
        
        let isLocal = apiUrl.contains("127.0.0.1") || apiUrl.contains("localhost") || apiUrl.contains("192.168")
        guard !savedKey.isEmpty || isLocal else {
            // Only alert them once so it doesn't spam their chat
            if !hasAlertedNoKey {
                isPolishing = true
                textDocumentProxy.insertText(" [🚨 API Key Missing] ")
                hasAlertedNoKey = true
                isPolishing = false
            }
            return
        }
        
        let finalKey = savedKey.isEmpty ? "lm-studio" : savedKey
        
        // Limit context to the last 150 characters to prevent the keyboard from lagging
        // while it tries to calculate massive diffs or rewrite entire paragraphs.
        let contextBound = 150
        let networkDraft = draftText.count > contextBound ? String(draftText.suffix(contextBound)) : draftText
        
        do {
            let response = try await fetchAIResponse(draft: networkDraft, tone: tone, apiKey: finalKey, apiUrl: apiUrl)
            
            // If they started typing heavily again, we toss this task out.
            if Task.isCancelled { return }
            
            isPolishing = true
            defer { isPolishing = false }
            
            // Re-apply original spacing because AI models often mistakenly drop them!
            var finalCorrected = response.corrected
            let draftTrailing = String(networkDraft.reversed().prefix(while: { $0.isWhitespace }).reversed())
            let correctedTrailing = String(finalCorrected.reversed().prefix(while: { $0.isWhitespace }).reversed())
            if !draftTrailing.isEmpty && correctedTrailing.isEmpty {
                finalCorrected += draftTrailing
            }
            
            let draftLeading = networkDraft.prefix(while: { $0.isWhitespace })
            let correctedLeading = finalCorrected.prefix(while: { $0.isWhitespace })
            if !draftLeading.isEmpty && correctedLeading.isEmpty {
                finalCorrected = draftLeading + finalCorrected
            }
            
            // Reattach the front part of the text that wasn't sent to the AI
            let untouchedPrefix = String(draftText.prefix(draftText.count - networkDraft.count))
            let fullPolishedDraft = untouchedPrefix + finalCorrected
            
            let currentContext = textDocumentProxy.documentContextBeforeInput ?? ""
            let newContext = applySmartReplacement(originalDraft: draftText, polishedDraft: fullPolishedDraft, currentContext: currentContext)
            
            // Update the state lock so it doesn't infinitely loop on itself
            self.lastObservedText = newContext
            
            // Pass the next-word predictions up to KeyboardKit
            smartProvider.aiPredictions = response.predictions
            updateAutocompleteUI()
            
        } catch {
            // Silently fail on network error to allow continuous typing...
            // UNLESS it's a local LM studio error, in which case we should alert them once!
            if isLocal && !self.hasAlertedNoKey {
                isPolishing = true
                let errStr = (error as NSError).localizedDescription
                textDocumentProxy.insertText(" [🚨 LM Studio Error: \(errStr)] ")
                self.hasAlertedNoKey = true
                isPolishing = false
            }
        }
    }
    
    // MARK: - Smart Diff Text Replacement
    
    private func applySmartReplacement(originalDraft: String, polishedDraft: String, currentContext: String) -> String {
        if originalDraft == polishedDraft { return currentContext } // No mistakes found!
        if currentContext == polishedDraft { return currentContext } // User already manually fixed it
        if currentContext.hasPrefix(polishedDraft) { return currentContext }
        
        // 🔥 SMART MERGE: If the user kept typing while the AI was thinking, seamlessly merge the fix!
        if currentContext.hasPrefix(originalDraft) {
            let extraTyped = String(currentContext.dropFirst(originalDraft.count))
            let targetContext = polishedDraft + extraTyped
            
            performTextReplacement(current: currentContext, target: targetContext)
            return targetContext
        }
        
        // If the user hit backspace or radically changed text while AI was thinking, safely abort
        if originalDraft.hasPrefix(currentContext) {
            return currentContext
        }
        
        return currentContext
    }
    
    private func performTextReplacement(current: String, target: String) {
        if current == target { return }
        
        let currentArr = Array(current)
        let targetArr = Array(target)
        let minLen = min(currentArr.count, targetArr.count)
        
        var commonPrefixLength = 0
        for i in 0..<minLen {
            if currentArr[i] == targetArr[i] {
                commonPrefixLength += 1
            } else {
                break
            }
        }
        
        let deleteCount = currentArr.count - commonPrefixLength
        let insertStr = String(targetArr[commonPrefixLength...])
        
        let softHaptic = UIImpactFeedbackGenerator(style: .soft)
        softHaptic.prepare()
        
        // Delete only the incorrect tail silently so it operates instantly
        for _ in 0..<deleteCount {
            textDocumentProxy.deleteBackward()
        }
        
        // Insert the corrected tail + anything the user typed in the meantime
        if !insertStr.isEmpty {
            textDocumentProxy.insertText(insertStr)
            softHaptic.impactOccurred(intensity: 0.6)
        }
    }
    
    // MARK: - AI Network Layer
    struct AIResponse {
        var corrected: String
        var predictions: [String]
    }
    
    private func fetchAIResponse(draft: String, tone: String, apiKey: String, apiUrl: String) async throws -> AIResponse {
        let endpoint = apiUrl.hasSuffix("/chat/completions") ? apiUrl : (apiUrl.hasSuffix("/") ? apiUrl + "chat/completions" : apiUrl + "/chat/completions")
        guard let url = URL(string: endpoint) else { throw URLError(.badURL) }
        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        
        // Local models (especially cold-start) can easily take > 5 seconds. Give it generous time.
        request.timeoutInterval = 30.0
        
        request.addValue("Bearer \(apiKey)", forHTTPHeaderField: "Authorization")
        request.addValue("application/json", forHTTPHeaderField: "Content-Type")
        
        let systemPrompt = """
        You are an invisible real-time iOS keyboard assistant. 
        Read the provided text context.
        1. Fix any typos, spelling, and grammar mistakes natively based on surrounding context.
        2. Adjust tone to [\(tone)] ONLY if it naturally fits. Keep the original meaning.
        3. Predict the next 3 logical words the user might type (single words only).
        
        CRITICAL: Output EXACTLY in this JSON format and nothing else. No markdown or explanation.
        {
          "corrected": "the fully polished text goes here",
          "predictions": ["word1", "word2", "word3"]
        }
        """
        
        let body: [String: Any] = [
            "model": "local-model", 
            "messages": [
                ["role": "system", "content": systemPrompt],
                ["role": "user", "content": draft]
            ],
            "temperature": 0.3
        ]
        
        request.httpBody = try JSONSerialization.data(withJSONObject: body)
        let config = URLSessionConfiguration.ephemeral
        let session = URLSession(configuration: config)
        let (data, response) = try await session.data(for: request)
        
        guard let httpResponse = response as? HTTPURLResponse, httpResponse.statusCode == 200 else {
            throw URLError(.badServerResponse)
        }
        
        if let json = try JSONSerialization.jsonObject(with: data) as? [String: Any],
           let choices = json["choices"] as? [[String: Any]],
           let message = choices.first?["message"] as? [String: Any],
           let content = message["content"] as? String {
            
            // Strip out <think> tags. (?s) allows Swift regex to cleanly bypass multiline reasoning blocks
            let strippedContent = content.replacingOccurrences(of: "(?s)<think>.*?</think>", with: "", options: .regularExpression)
            
            // Robustly extract the JSON payload if wrapped in markdown blocks
            var jsonString = strippedContent.trimmingCharacters(in: .whitespacesAndNewlines)
            if jsonString.hasPrefix("```json") { jsonString = String(jsonString.dropFirst(7)) }
            else if jsonString.hasPrefix("```") { jsonString = String(jsonString.dropFirst(3)) }
            if jsonString.hasSuffix("```") { jsonString = String(jsonString.dropLast(3)) }
            jsonString = jsonString.trimmingCharacters(in: .whitespacesAndNewlines)
            
            if let jsonData = jsonString.data(using: .utf8),
               let parsed = try JSONSerialization.jsonObject(with: jsonData) as? [String: Any] {
                let corrected = parsed["corrected"] as? String ?? draft
                let predictions = parsed["predictions"] as? [String] ?? []
                return AIResponse(corrected: corrected, predictions: predictions)
            }
        }
        
        throw URLError(.cannotParseResponse)
    }
}